//! Numbers that cross the 128-bit limit (about 1.7e38) or have many places: sums, products
//! through `@` and `@@`, inferred prices rounded at 255 places, balance assertions and
//! assignments, valuation and holdings. A wrong digit shows where a number stops fitting in the
//! machine word and moves to the arbitrary-precision path. Expected values: hledger 1.52.4 on
//! the named `decimal-*` probes (`print -O json`, with `--cost` and `--value`, and
//! `balance --layout=tidy -O json --real` for the holdings, which agree with hledger by value),
//! written out as exact decimal strings.
// Integration tests are compiled outside `cfg(test)`; a panic here is a failed test.
#![allow(clippy::unwrap_used, clippy::expect_used)]

mod support;

use ledgermill::{HoldingsQuery, Quantity, load};
use serde_json::json;
use support::*;

macro_rules! probe {
    ($name:literal) => {
        (
            concat!($name, ".journal"),
            include_str!(concat!("../../../spec/hledger/probes/", $name, ".journal")),
        )
    };
}

/// The short form of `spec/hledger/show-amounts.sh`, one line per transaction.
fn tx(probe: (&str, &str)) -> Vec<String> {
    short_lines(load(&[file(probe.0, probe.1)]).transactions())
}

/// `DATE ACCOUNT NUMBER COMMODITY` for each posting.
fn postings(probe: (&str, &str)) -> Vec<String> {
    load(&[file(probe.0, probe.1)])
        .postings()
        .iter()
        .map(|p| format!("{} {} {} {}", p.date, p.account, p.number, p.currency))
        .map(|line| line.trim_end().to_string())
        .collect()
}

fn amounts(list: &[Quantity]) -> String {
    if list.is_empty() {
        return "-".into();
    }
    let parts: Vec<String> = list
        .iter()
        .map(|q| format!("{} {}", q.commodity, q.quantity))
        .collect();
    parts.join(", ")
}

/// `ACCOUNT [COMMODITY] | units | cost | value | cost value`, one line per holding.
fn holdings(probe: (&str, &str), commodity: &str, end: Option<&str>) -> Vec<String> {
    let query = HoldingsQuery {
        commodity: commodity.into(),
        end: end.map(Into::into),
        today: "2026-11-10".into(),
    };
    load(&[file(probe.0, probe.1)])
        .holdings(&query)
        .unwrap()
        .iter()
        .map(|h| {
            format!(
                "{} [{}] | {} | {} | {} | {}",
                h.account,
                h.commodity,
                h.units,
                amounts(&h.cost),
                amounts(&h.value),
                amounts(&h.cost_value)
            )
        })
        .collect()
}

/// `[line, code]` of each finding of a journal given as text.
fn failures(text: &str) -> serde_json::Value {
    let rows: Vec<_> = short_findings("fail.journal", text)
        .as_array()
        .unwrap()
        .iter()
        .map(|f| json!([f[0], f[1]]))
        .collect();
    json!(rows)
}

