    let text = "2026-01-01 a\n    a  170141183460469231731687303715884105728 X\n    b  -170141183460469231731687303715884105728 X\n\n2026-01-02 b\n    a  -170141183460469231731687303715884105728 X = 1 X\n    b  170141183460469231731687303715884105728 X\n";
